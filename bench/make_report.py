"""Generate the results tables the README embeds.

Committed script, committed parquet, generated table: the numbers in the
writeup can be regenerated by anyone who clones the repo, and a number that
cannot be regenerated does not go in.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))

from analyze import across_seeds, load, summarize  # noqa: E402

LABELS = {
    "fifo": "1  FIFO, no batching",
    "static": "2  Static batching (8)",
    "continuous": "3  Continuous batching",
    "continuous+cache": "4  + paged KV + prefix cache",
    "continuous+cache+admission": "5  + conformal admission",
}
ORDER = list(LABELS)


def _order(s: pd.DataFrame) -> pd.DataFrame:
    s = s.copy()
    s["_k"] = s.config.map({c: i for i, c in enumerate(ORDER)}).fillna(99)
    return s.sort_values(["_k", "rate_rps"]).drop(columns="_k")


def ladder_table(s: pd.DataFrame, df: pd.DataFrame, slo: float) -> str:
    """One row per rung: the five columns that make each row attributable."""
    rows = []
    for cfg in [c for c in ORDER if c in set(s.config)]:
        g = s[s.config == cfg].sort_values("rate_rps")
        peak = g.loc[g.goodput_rps.idxmax()]
        # p99 at roughly twice the rung's own saturation point.
        sat = float(peak.rate_rps)
        over = g[g.rate_rps >= 2 * sat]
        over_row = over.iloc[0] if len(over) else g.iloc[-1]
        hit = df[(df.config == cfg)].get("prefix_hit_rate_server")
        rows.append(
            {
                "Config": LABELS[cfg],
                f"Peak goodput (rps, SLO {slo:g}s)": f"{peak.goodput_rps:.2f}",
                "at offered": f"{sat:.1f}",
                "p50 TTFT (s)": f"{peak.ttft_p50:.2f}",
                "p99 TTFT (s)": f"{peak.ttft_p99:.2f}",
                f"p99 E2E at {over_row.rate_rps:.1f} rps": f"{over_row.e2e_p99:.1f}",
                "Prefix hit rate": (
                    f"{float(hit.dropna().iloc[-1]):.0%}"
                    if hit is not None and hit.notna().any()
                    else "n/a"
                ),
            }
        )
    return pd.DataFrame(rows).to_markdown(index=False)


def sweep_table(s: pd.DataFrame) -> str:
    cols = {
        "config": "Config", "rate_rps": "Offered (rps)", "n": "Requests",
        "throughput_rps": "Throughput", "goodput_rps": "Goodput",
        "slo_attainment": "SLO met", "ttft_p50": "TTFT p50", "ttft_p99": "TTFT p99",
        "itl_p50": "ITL p50", "itl_p99": "ITL p99",
        "e2e_p50": "E2E p50", "e2e_p99": "E2E p99",
    }
    v = _order(s)[list(cols)].rename(columns=cols)
    for c in v.columns:
        if v[c].dtype.kind == "f":
            v[c] = v[c].map(lambda x: "-" if pd.isna(x) else f"{x:.3f}")
    return v.to_markdown(index=False)


def slo_sensitivity(df: pd.DataFrame, slos=(2.0, 3.0, 4.0, 6.0, 8.0)) -> str:
    """The SLO is a choice, so its effect is shown rather than asserted."""
    rows = []
    for slo in slos:
        s = summarize(df, slo_s=slo)
        row = {"SLO (s)": f"{slo:g}"}
        for cfg in [c for c in ORDER if c in set(s.config)]:
            g = s[s.config == cfg]
            row[LABELS[cfg].split("  ", 1)[1]] = f"{g.goodput_rps.max():.2f}"
        rows.append(row)
    return pd.DataFrame(rows).to_markdown(index=False)


def methodology_block(df: pd.DataFrame) -> str:
    lines = [
        f"- Runs: {df.groupby(['config', 'rate_rps', 'seed']).ngroups} "
        f"({df.config.nunique()} configurations x {df.rate_rps.nunique()} offered loads "
        f"x {df.seed.nunique()} seed)",
        f"- Requests issued: {len(df):,}; analysed in steady state: {int(df.steady.sum()):,}",
        f"- Per run: {df.duration_s.iloc[0]:.0f}s of arrivals, first "
        f"{df.warmup_s.iloc[0]:.0f}s and last {df.cooldown_s.iloc[0]:.0f}s excluded "
        f"from every quantile",
    ]
    if "ks_p" in df:
        # One arrival *realisation* per (rate, seed) -- every rung replays the
        # same one, which is what makes the rungs comparable. Counting it once
        # per run would report a single draw as N independent pieces of
        # evidence.
        ks = df.groupby(["rate_rps", "seed"]).ks_p.first()
        lines.append(
            f"- Inter-arrival KS test against Exp(lambda), one per distinct arrival "
            f"realisation: {int((ks > 0.05).sum())}/{len(ks)} pass at alpha=0.05 "
            f"(median p = {ks.median():.3f}). See `results/loadgen_validation.json` "
            f"and the note below."
        )
    if "sched_delay" in df:
        lines.append(
            f"- Client-side scheduling slip (actual send minus intended arrival): "
            f"p99 {df.sched_delay.quantile(0.99) * 1e3:.1f} ms, "
            f"max {df.sched_delay.max() * 1e3:.0f} ms"
        )
    return "\n".join(lines)


def main(argv=None) -> None:
    p = argparse.ArgumentParser()
    p.add_argument("paths", nargs="+")
    p.add_argument("--slo", type=float, default=4.0)
    p.add_argument("--outdir", default="docs")
    a = p.parse_args(argv)

    out = Path(a.outdir)
    out.mkdir(parents=True, exist_ok=True)
    df = load(a.paths)
    s = summarize(df, slo_s=a.slo)

    (out / "ladder.md").write_text(ladder_table(s, df, a.slo) + "\n")
    (out / "sweep.md").write_text(sweep_table(s) + "\n")
    (out / "slo_sensitivity.md").write_text(slo_sensitivity(df) + "\n")
    (out / "methodology.md").write_text(methodology_block(df) + "\n")
    s.to_csv(out / "summary.csv", index=False)
    if df.seed.nunique() > 1:
        across_seeds(s).to_csv(out / "summary_by_seed.csv", index=False)

    print(ladder_table(s, df, a.slo))
    print()
    print(sweep_table(s))
    print()
    print(methodology_block(df))


if __name__ == "__main__":
    main()
